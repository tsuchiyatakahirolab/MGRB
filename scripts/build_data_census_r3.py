def source(
    source_id: str,
    provider: str,
    product: str,
    url: str,
    actors: str,
    evidence: str,
    geography: str,
    access: str,
    license_name: str,
    priority: str,
    suitability: str,
    *,
    languages: str = "English",
    temporal: str = "varies",
    cadence: str = "varies",
    identity: str = "none or provider-dependent",
    density: str = "provider-dependent",
    temporal_resolution: str = "provider-dependent",
    precision: str = "provider-dependent",
    processing: str = "provider-dependent",
    quality: str = "documented by provider",
    uncertainty: str = "not explicit",
    fmt: str = "web/report",
    qgis: str = "requires connector or digitization",
    retrieval: str = "",
    attribution: str = "required",
    redistribution: str = "review terms",
    commercial: str = "review terms",
    citation: str = "cite provider/product",
    default: str = "NO",
    reason: str = "",
) -> dict[str, str]:
    return {
        "source_id": source_id,
        "provider": provider,
        "product": product,
        "url": url,
        "languages": languages,
        "actor_families": actors,
        "evidence_type": evidence,
        "geographic_coverage": geography,
        "temporal_coverage": temporal,
        "update_cadence_or_lag": cadence,
        "identity_fields": identity,
        "spatial_density_or_resolution": density,
        "temporal_resolution": temporal_resolution,
        "coordinate_precision": precision,
        "processing_level": processing,
        "quality_flags": quality,
        "uncertainty_model": uncertainty,
        "format": fmt,
        "qgis_readiness": qgis,
        "access_class": access,
        "retrieval_test_id": retrieval,
        "license_or_terms": license_name,
        "attribution_required": attribution,
        "redistribution": redistribution,
        "commercial_use": commercial,
        "recommended_citation": citation,
        "production_suitability": suitability,
        "connector_priority": priority,
        "default_eligible": default,
        "decision_reason": reason,
        "last_checked_utc": CHECKED,
    }


